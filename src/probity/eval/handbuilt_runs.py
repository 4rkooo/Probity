BBox = tuple[int, int, int, int]

HANDBUILT_NOTE = (
    "HAND-BUILT GOLDEN (step 1): donor geometry is the synthetic generator's ground-truth "
    "translation standing in for AKAZE/RANSAC; regenerated by the TrueFrame pipeline in step 8."
)
SYNTHETIC_NOTE = "Synthetic evaluation window; no real scene, vehicle, or plate."
RUN_START = "2026-10-09T17:10:00.000000Z"
R_WEIGHTS = {"Q": 0.45, "A": 0.35, "T": 0.20}
A_WEIGHTS = {"inlier": 0.40, "reprojection": 0.30, "coverage": 0.30}
SELECT_WEIGHTS = {"improvement": 0.50, "rank": 0.30, "residual": 0.20}


@dataclass
class Donor:
    obs: TrackObservation
    frame_number: int
    image: np.ndarray
    quality: q.QualityComponents
    dt_s: float
    tx: float = 0.0
    ty: float = 0.0
    alignment: float = 0.0
    temporal: float = 0.0
    rank: float = 0.0
    warped: np.ndarray | None = None
    lut_index: int = 0
    decision_ids: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class HandbuiltRun:
    run: ReconstructionRun
    decisions: tuple[PolicyDecision, ...]
    provenance: PixelProvenance | None = None
    arrays: ProvenanceArrays | None = None
    result_png: bytes | None = None
    npz: bytes | None = None
    assets: tuple[AssetRef, ...] = ()


def _ring_mask(shape: tuple[int, int], expanded: BBox, subject: BBox) -> np.ndarray:
    mask = np.zeros(shape, dtype=bool)
    ex1, ey1, ex2, ey2 = expanded
    sx1, sy1, sx2, sy2 = subject
    mask[ey1:ey2, ex1:ex2] = True
    mask[sy1:sy2, sx1:sx2] = False
    return mask


def _low_gradient(luma: np.ndarray, max_gradient_8bit: int) -> np.ndarray:
    g = luma.astype(np.float32) / 255.0
    gx = cv2.Sobel(g, cv2.CV_32F, 1, 0, ksize=3)
    gy = cv2.Sobel(g, cv2.CV_32F, 0, 1, ksize=3)
    return np.asarray(np.sqrt(gx * gx + gy * gy) <= max_gradient_8bit / 255.0)


def build_handbuilt_run(window: WindowBundle, cfg: PolicyConfig, run_label: str) -> HandbuiltRun:
    truth = load_truth(window.root)  # EVALUATION ONLY: hand-built geometry stand-in.
    clock = FixedClock(RUN_START)
    run_id = seeded_uuid7(f"{window.fixture_id}:{run_label}:run", clock.unix_ms)
    log = DecisionLog(run_id, clock)
    resolve = window.resolver
    detections: dict[str, list[Detection]] = {}
    for det in window.detections:
        detections.setdefault(det.frame_id, []).append(det)
    track = window.track
    started_at = clock.at(0)

    log.add(ReasonCode.FIXTURE_MODE_DISCLOSED, PolicyStage.MODE, "inputs", PolicyOutcome.WARN,
            "Synthetic fixture window and hand-built golden run", observed="FIXTURE",
            operator="==", threshold="FIXTURE")

    images = {ref.frame_number: load_frame(ref, resolve) for ref in window.frames}
    digest = source_digest([ref.pixel_sha256 or "" for ref in window.frames])
    if digest != window.source_sha256:
        raise ValueError("synthetic source digest mismatch")
    log.add(ReasonCode.SOURCE_HASH_VERIFIED, PolicyStage.INPUT, "source", PolicyOutcome.ACCEPT,
            "Frame pixel hashes re-verified; synthetic source digest matched", observed=digest[:12],
            operator="==", threshold=window.source_sha256[:12])

    target_n = parse_frame_id(window.target_frame_id)[1]
    target_ref = window.frame(target_n)
    tbox: BBox = window.target_bbox_px

    def refused(reason: ReasonCode, iterations: int, accepted_ids: tuple[str, ...] = ()
                ) -> HandbuiltRun:
        run = ReconstructionRun.create(
            created_at=clock.at(len(log.rows) + 1),
            run_id=run_id, case_id=window.case_id, video_id=window.video_id,
            track_id=track.track_id, target_frame_id=target_ref.frame_id,
            target_pts_us=target_ref.pts_us, target_bbox_px=tbox,
            state=ReconstructionState.REFUSED, config_sha256=cfg.config_sha256,
            iteration_count=iterations, accepted_donor_frame_ids=accepted_ids,
            policy_decision_ids=log.ids, refusal_reasons=(reason,),
            uncertainty=("No defensible enhancement produced; the original frame is unchanged.",
                         SYNTHETIC_NOTE, HANDBUILT_NOTE),
            mode=InferenceMode.FIXTURE, started_at=started_at,
            finished_at=clock.at(len(log.rows) + 1),
        )
        return HandbuiltRun(run=run, decisions=log.rows)

    pre = run_preflight(
        log, track=track, video_id=window.video_id, case_id=window.case_id,
        target_frame_id=window.target_frame_id, target_box=tbox,
        frames={ref.frame_id: ref for ref in window.frames},
        load=lambda ref: images[ref.frame_number], detections=detections, cfg=cfg)
    if pre.refusal is not None:
        return refused(pre.refusal, 0)
    assert pre.target is not None
    target = pre.target.image
    H, W = target.shape[:2]
    target_luma = q.crop(q.to_luma(target), tbox)

    expanded_t = q.expand_box(tbox, cfg.crop.alignment_context_expand, W, H)
    donors = [Donor(obs=m.obs, frame_number=m.frame_number, image=m.image, quality=m.quality,
                    dt_s=m.dt_s, decision_ids=list(m.decision_ids)) for m in pre.donors]

    # Geometry (HAND-BUILT stand-in) and color compatibility.
    ys, xs = np.indices((H, W), dtype=np.float32)
    ring = _ring_mask((H, W), expanded_t, tbox)
    stable = ring & _low_gradient(q.to_luma(target), cfg.color.max_context_gradient_8bit)
    origins = {f["frame_number"]: f["plate_origin"] for f in truth["frames"]}
    compatible: list[Donor] = []
    for d in donors:
        t_origin, d_origin = origins[target_n], origins[d.frame_number]
        d.tx, d.ty = t_origin[0] - d_origin[0], t_origin[1] - d_origin[1]
        map_x, map_y = xs - np.float32(d.tx), ys - np.float32(d.ty)
        ex1, ey1, ex2, ey2 = expanded_t
        mx, my = map_x[ey1:ey2, ex1:ex2], map_y[ey1:ey2, ex1:ex2]
        inside = (mx >= 0) & (mx <= W - 1) & (my >= 0) & (my <= H - 1)
        coverage = float(inside.mean())
        d.alignment = (A_WEIGHTS["inlier"] * 1.0 + A_WEIGHTS["reprojection"] * 1.0
                       + A_WEIGHTS["coverage"] * coverage)
        ok = log.gate(ReasonCode.ALIGNMENT_AKAZE_ACCEPTED, PolicyStage.ALIGN, d.obs.frame_id,
                      observed=coverage, operator=">=", threshold=cfg.alignment.min_valid_coverage,
                      units="fraction", policy_key="alignment.min_valid_coverage",
                      accept_reason=f"Valid warp coverage passed. {HANDBUILT_NOTE}",
                      reject_reason="Warp coverage below minimum")
        d.decision_ids.append(log.ids[-1])
        if not ok:
            continue
        d.warped = cv2.remap(d.image, map_x, map_y, cv2.INTER_LANCZOS4,
                             borderMode=cv2.BORDER_REFLECT_101)
        sel = stable & (map_x >= 0) & (map_x <= W - 1) & (map_y >= 0) & (map_y <= H - 1)
        samples = int(sel.sum())
        ok = log.gate(ReasonCode.PHOTOMETRIC_INCOMPATIBLE, PolicyStage.COLOR, d.obs.frame_id,
                      observed=samples, operator=">=", threshold=cfg.color.min_context_samples,
                      units="samples", policy_key="color.min_context_samples",
                      accept_reason="Enough stable context-ring samples",
                      reject_reason="Too few stable context-ring samples")
        d.decision_ids.append(log.ids[-1])
        if not ok:
            continue
        residual = float(np.abs(d.warped[sel].astype(np.float64)
                                - target[sel].astype(np.float64)).mean())
        ok = log.gate(ReasonCode.PHOTOMETRIC_INCOMPATIBLE, PolicyStage.COLOR, d.obs.frame_id,
                      observed=residual, operator="<=",
                      threshold=cfg.color.max_mean_abs_residual_8bit, units="8bit",
                      policy_key="color.max_mean_abs_residual_8bit",
                      accept_reason="Context-ring residual within limit (identity gain/bias)",
                      reject_reason="Context-ring residual exceeds limit")
        d.decision_ids.append(log.ids[-1])
        if ok:
            compatible.append(d)

    for d in compatible:
        d.temporal = math.exp(-abs(d.dt_s) / cfg.donor.temporal_decay_s)
        d.rank = (R_WEIGHTS["Q"] * d.quality.Q + R_WEIGHTS["A"] * d.alignment
                  + R_WEIGHTS["T"] * d.temporal)
    ranked = sorted(compatible, key=lambda d: (-d.rank, d.frame_number))[: cfg.donor.max_count]
    enough = log.gate(ReasonCode.INSUFFICIENT_COMPATIBLE_DONORS, PolicyStage.RANK, "donors",
                      observed=len(ranked), operator=">=", threshold=cfg.donor.min_count,
                      units="donors", policy_key="donor.min_count",
                      accept_reason="Enough compatible donors",
                      reject_reason="Fewer compatible donors than required")
    accepted_ids = tuple(d.obs.frame_id for d in ranked)
    if not enough:
        return refused(ReasonCode.INSUFFICIENT_COMPATIBLE_DONORS, 0, accepted_ids)

    # Winner-take-all 8x8 tiles; never averages donors.
    tx1, ty1, tx2, ty2 = tbox
    rel_tiles = [(a - tx1, b - ty1, c - tx1, e - ty1)
                 for a, b, c, e in q.tiles(tbox, cfg.fusion.tile_px)]
    s_target = q.tile_sharpness_scores(target_luma, rel_tiles, cfg)
    s_donor: dict[int, list[float]] = {}
    for d in ranked:
        assert d.warped is not None
        s_donor[id(d)] = q.tile_sharpness_scores(q.crop(q.to_luma(d.warped), tbox), rel_tiles, cfg)
    for i, d in enumerate(ranked, start=1):
        d.lut_index = i
    arrays = ProvenanceArrays.identity(W, H)
    result = target.copy()
    kept_clear = kept_no_gain = kept_residual = 0
    borrowed_px: dict[int, int] = {d.lut_index: 0 for d in ranked}
    eps = cfg.fusion.sharpness_ratio_epsilon
    max_res = cfg.color.max_mean_abs_residual_8bit
    for i, (a, b, c, e) in enumerate(rel_tiles):
        x1, y1, x2, y2 = a + tx1, b + ty1, c + tx1, e + ty1
        if s_target[i] >= cfg.fusion.keep_original_sharpness:
            kept_clear += 1
            continue
        best: tuple[float, Donor, float, float] | None = None
        any_gain = False
        for d in ranked:
            imp = (s_donor[id(d)][i] - s_target[i]) / max(s_target[i], eps)
            if imp < cfg.fusion.min_sharpness_improvement:
                continue
            any_gain = True
            mx = xs[y1:y2, x1:x2] - np.float32(d.tx)
            my = ys[y1:y2, x1:x2] - np.float32(d.ty)
            cover = float(((mx >= 0) & (mx <= W - 1) & (my >= 0) & (my <= H - 1)).mean())
            if cover < cfg.fusion.required_valid_tile_coverage:
                continue
            assert d.warped is not None
            res = float(np.abs(d.warped[y1:y2, x1:x2].astype(np.float64)
                               - target[y1:y2, x1:x2].astype(np.float64)).mean())
            if res > max_res:
                continue
            score = (SELECT_WEIGHTS["improvement"] * imp + SELECT_WEIGHTS["rank"] * d.rank
                     + SELECT_WEIGHTS["residual"] * (1.0 - res / max_res))
            if best is None or score > best[0]:
                best = (score, d, imp, res)
        if best is None:
            if any_gain:
                kept_residual += 1
            else:
                kept_no_gain += 1
            continue
        _, d, imp, res = best
        assert d.warped is not None
        result[y1:y2, x1:x2] = d.warped[y1:y2, x1:x2]
        arrays.cls[y1:y2, x1:x2] = ProvenanceClass.BORROWED
        arrays.source_index[y1:y2, x1:x2] = d.lut_index
        arrays.source_x[y1:y2, x1:x2] = xs[y1:y2, x1:x2] - np.float32(d.tx)
        arrays.source_y[y1:y2, x1:x2] = ys[y1:y2, x1:x2] - np.float32(d.ty)
        borrowed_px[d.lut_index] += (x2 - x1) * (y2 - y1)
        log.gate(ReasonCode.BORROW_TILE_ACCEPTED, PolicyStage.FUSE, f"tile:{x1},{y1}",
                 observed=imp, operator=">=", threshold=cfg.fusion.min_sharpness_improvement,
                 units="ratio", policy_key="fusion.min_sharpness_improvement",
                 accept_reason=f"Borrowed from {d.obs.frame_id}; residual {res:.2f}/255",
                 reject_reason="Sharpness improvement below minimum")
        d.decision_ids.append(log.ids[-1])
    n_kept = kept_clear + kept_no_gain + kept_residual
    log.add(ReasonCode.KEEP_ORIGINAL_CLEAR, PolicyStage.FUSE, "tiles", PolicyOutcome.ACCEPT,
            f"Kept original: {kept_clear} already clear, {kept_no_gain} not improved, "
            f"{kept_residual} failed residual/coverage", observed=n_kept, operator=">=",
            threshold=0, units="tiles", policy_key="fusion.keep_original_sharpness")
    n_borrowed = sum(borrowed_px.values())
    if n_borrowed == 0:
        log.add(ReasonCode.NO_TILE_IMPROVED, PolicyStage.FUSE, "tiles", PolicyOutcome.REJECT,
                "No tile met the improvement and residual gates", observed=0, operator=">=",
                threshold=1, units="tiles", policy_key="fusion.min_sharpness_improvement")
        return refused(ReasonCode.NO_TILE_IMPROVED, 1, accepted_ids)

    lut = [SourceLutEntry(index=0, frame_id=target_ref.frame_id,
                          frame_number=target_ref.frame_number, pts_us=target_ref.pts_us,
                          role=SourceRole.TARGET, alignment_method=AlignmentMethod.IDENTITY,
                          interpolation=Interpolation.IDENTITY)]
    for d in ranked:
        lut.append(SourceLutEntry(
            index=d.lut_index, frame_id=d.obs.frame_id, frame_number=d.frame_number,
            pts_us=d.obs.pts_us, role=SourceRole.DONOR, transform_id=f"gt_{d.frame_number}",
            alignment_method=AlignmentMethod.AKAZE_HOMOGRAPHY,
            matrix=(1.0, 0.0, float(d.tx), 0.0, 1.0, float(d.ty), 0.0, 0.0, 1.0),
            interpolation=Interpolation.LANCZOS4, color_gain=(1.0, 1.0, 1.0),
            color_bias=(0.0, 0.0, 0.0), decision_ids=tuple(d.decision_ids)))
    sizes = {e.index: (W, H) for e in lut}
    counts = validate_arrays(arrays, W, H, lut, sizes)
    assert_supported_changes(result, target, arrays)
    log.add(ReasonCode.PROVENANCE_COMPLETE, PolicyStage.PROVENANCE, run_id, PolicyOutcome.ACCEPT,
            "Every output pixel resolves", observed=1.0, operator="==",
            threshold=cfg.integrity.required_provenance_coverage, units="fraction",
            policy_key="integrity.required_provenance_coverage")
    log.add(ReasonCode.GENERATED_SEMANTIC_PIXEL, PolicyStage.PROVENANCE, run_id,
            PolicyOutcome.ACCEPT, "No generated pixels", observed=0.0, operator="<=",
            threshold=cfg.integrity.max_semantic_generated_fraction, units="fraction",
            policy_key="integrity.max_semantic_generated_fraction")

    qd = sum(borrowed_px[d.lut_index] * d.quality.Q for d in ranked) / n_borrowed
    ad = sum(borrowed_px[d.lut_index] * d.alignment for d in ranked) / n_borrowed
    components = dict(supported_coverage=1.0, mean_source_confidence=round(qd, 6),
                      mean_alignment_confidence=round(ad, 6),
                      track_continuity=track.continuity_score, audit_completeness=1.0,
                      semantic_generated_pct=0.0)
    score = integrity_score_0_100(**components)
    integrity = IntegrityScore(score_0_100=score, **components)
    ok = log.gate(ReasonCode.INTEGRITY_BELOW_MINIMUM, PolicyStage.INTEGRITY, run_id,
                  observed=score, operator=">=", threshold=cfg.integrity.min_score,
                  units="points", policy_key="integrity.min_score",
                  accept_reason="Integrity meets minimum", reject_reason="Integrity below minimum")
    if not ok:
        return refused(ReasonCode.INTEGRITY_BELOW_MINIMUM, 1, accepted_ids)

    png = encode_png(result)
    npz = encode_provenance(arrays)
    npz_sha = sha256_bytes(npz)
    full_pct = coverage_pct(counts, W * H)
    subj_pct = subject_coverage_pct(arrays, tbox)
    finished = clock.at(len(log.rows) + 1)
    derived = f"derived/{window.video_id}/reconstruction/{run_id}/provenance.npz"
    provenance = PixelProvenance.create(
        created_at=finished, run_id=run_id, width_px=W, height_px=H, subject_bbox_px=tbox,
        class_map_uri=derived, source_index_uri=derived, source_xy_uri=derived,
        source_lut=tuple(lut), coverage_counts=counts, coverage_pct=full_pct,
        subject_coverage_pct=subj_pct, coverage_complete=True, artifact_sha256=npz_sha)
    out_rel = f"fixtures/synthetic/{window.fixture_id}/reconstructions/{run_label}"
    lut_json = json_bytes(provenance)

    def asset(kind: AssetKind, name: str, media: str, data: bytes) -> AssetRef:
        return AssetRef(asset_id=seeded_uuid7(f"{run_id}:asset:{name}", clock.unix_ms + 900),
                        case_id=window.case_id, kind=kind, storage_uri=f"{out_rel}/{name}",
                        media_type=media, byte_length=len(data), sha256=sha256_bytes(data),
                        non_evidentiary=False, created_at=finished)

    assets = (asset(AssetKind.RESULT_PNG, "result.png", "image/png", png),
              asset(AssetKind.PROVENANCE_NPZ, "provenance.npz", "application/x-npz", npz),
              asset(AssetKind.PROVENANCE_LUT, "provenance.json", "application/json", lut_json))
    run = ReconstructionRun.create(
        created_at=finished, run_id=run_id, case_id=window.case_id, video_id=window.video_id,
        track_id=track.track_id, target_frame_id=target_ref.frame_id,
        target_pts_us=target_ref.pts_us, target_bbox_px=tbox,
        state=ReconstructionState.SUCCEEDED, config_sha256=cfg.config_sha256, iteration_count=1,
        accepted_donor_frame_ids=accepted_ids,
        result_png_uri=f"asset://{assets[0].asset_id}",
        provenance_uri=f"asset://{assets[1].asset_id}",
        provenance=ProvenanceSummary(coverage_pct=full_pct, subject_coverage_pct=subj_pct,
                                     coverage_complete=True, source_lut=tuple(lut)),
        result_png_sha256=sha256_bytes(png), provenance_sha256=npz_sha,
        policy_decision_ids=log.ids, integrity=integrity,
        uncertainty=("Result may remain blurry where no compatible donor was clearer.",
                     "Color and geometry transforms alter the appearance of borrowed pixels.",
                     SYNTHETIC_NOTE, HANDBUILT_NOTE),
        mode=InferenceMode.FIXTURE, started_at=started_at, finished_at=finished)
    return HandbuiltRun(run=run, decisions=log.rows, provenance=provenance, arrays=arrays,
                        result_png=png, npz=npz, assets=assets)


def write_handbuilt_run(built: HandbuiltRun, out_dir: Path) -> None:
    atomic_write_bytes(out_dir / "run.json", json_bytes(built.run))
    atomic_write_bytes(out_dir / "decisions.json", json_bytes(list(built.decisions)))
    if built.provenance is not None:
        assert built.result_png is not None
        assert built.npz is not None
        atomic_write_bytes(out_dir / "result.png", built.result_png)
        atomic_write_bytes(out_dir / "provenance.npz", built.npz)
        atomic_write_bytes(out_dir / "provenance.json", json_bytes(built.provenance))
        atomic_write_bytes(out_dir / "assets.json", json_bytes(list(built.assets)))
        for a in built.assets:
            if file_sha256(out_dir / Path(a.storage_uri).name) != a.sha256:
                raise RuntimeError(f"{a.storage_uri} hash mismatch after write")


GOLDEN_RUNS: Sequence[tuple[str, str]] = (
    ("plate_translate_v1", "completed"),
    ("plate_single_donor_v1", "refused"),
)


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Regenerate hand-built golden runs (step 1)")
    parser.add_argument("--root", type=Path, default=Path("fixtures") / "synthetic")
    args = parser.parse_args(argv)
    cfg = default_policy()
    for fixture_id, label in GOLDEN_RUNS:
        window = load_window(args.root / fixture_id)
        built = build_handbuilt_run(window, cfg, label)
        out = args.root / fixture_id / "reconstructions" / label
        write_handbuilt_run(built, out)
        print(out, built.run.state, built.run.refusal_reasons or built.run.integrity)


if __name__ == "__main__":
    main()
