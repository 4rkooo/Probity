"""HAND-BUILT GOLDEN RUNS (step 1). NOT TrueFrame output.

Builds one completed and one REFUSED ``ReconstructionRun`` from the committed synthetic windows so
the UI can integrate before the pipeline exists. The section 9 quality, pre-alignment, color
residual, tile-selection, and provenance rules are applied with the real policy values. The one
substitution: donor geometry is the generator's ground-truth translation instead of
AKAZE/RANSAC. That substitution is disclosed in every run's ``uncertainty`` and in the alignment
decisions. Step 8 regenerates these runs from ``reconstruction/trueframe.py`` and deletes this
module.

Every provenance invariant still holds: full-frame arrays, no class-2 pixels, every source index
resolves, every coordinate is finite and in bounds, and every changed pixel is BORROWED.

Regenerate:  uv run python -m probity.eval.handbuilt_runs
"""

