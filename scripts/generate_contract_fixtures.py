def ffprobe_frames() -> tuple[str, list[dict[str, Any]], str]:
    out = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "v:0",
            "-show_frames",
            "-show_entries",
            "frame=pts,best_effort_timestamp,key_frame,width,height:stream=time_base",
            "-of",
            "json",
            str(SOURCE),
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    data = json.loads(out)
    version = subprocess.run(
        ["ffprobe", "-version"], check=True, capture_output=True, text=True
    ).stdout.splitlines()[0]
    return data["streams"][0]["time_base"], data["frames"], version


def decode_frame(n: int) -> np.ndarray:
    png = subprocess.run(
        [
            "ffmpeg",
            "-v",
            "error",
            "-i",
            str(SOURCE),
            "-vf",
            f"select=eq(n\\,{n})",
            "-fps_mode",
            "passthrough",
            "-frames:v",
            "1",
            "-f",
            "image2pipe",
            "-vcodec",
            "png",
            "-",
        ],
        check=True,
        capture_output=True,
    ).stdout
    return np.array(Image.open(io.BytesIO(png)).convert("RGB"))


def plate_bbox(img: np.ndarray) -> tuple[int, int, int, int]:
    region = img[380:540]
    mask = (region > 225).all(axis=2)
    ys, xs = np.nonzero(mask)
    return int(xs.min()), int(ys.min()) + 380, int(xs.max()) + 1, int(ys.max()) + 381


