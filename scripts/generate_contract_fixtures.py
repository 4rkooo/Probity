def det_uuid7(label: str, offset_ms: int = 0) -> str:
    digest = hashlib.sha256(label.encode()).digest()
    raw = bytearray((BASE_MS + offset_ms).to_bytes(6, "big") + digest[:10])
    raw[6] = 0x70 | (raw[6] & 0x0F)
    raw[8] = 0x80 | (raw[8] & 0x3F)
    h = raw.hex()
    return f"{h[:8]}-{h[8:12]}-{h[12:16]}-{h[16:20]}-{h[20:]}"


def ts(offset_s: float) -> str:
    whole = int(offset_s)
    micros = round((offset_s - whole) * 1_000_000)
    h, rem = divmod(16 * 3600 + whole, 3600)
    m, s = divmod(rem, 60)
    return f"2026-10-09T{h:02d}:{m:02d}:{s:02d}.{micros:06d}Z"


def fake_sha(label: str) -> str:
    return hashlib.sha256(f"probity-contract-mock:{label}".encode()).hexdigest()


def file_sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def dump(name: str, payload: Any) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    data: Any
    if isinstance(payload, list):
        data = [p.model_dump(mode="json") for p in payload]
    else:
        data = payload.model_dump(mode="json")
    (OUT / name).write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


